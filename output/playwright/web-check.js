async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  await page.goto('http://127.0.0.1:8088/web/');
  await page.evaluate(() => localStorage.removeItem('decisor-web-state'));
  await page.reload();
  await page.setViewportSize({width: 390, height: 844});
  await page.emulateMedia({reducedMotion: 'no-preference'});
  await page.locator('#mode-selector').click();
  await page.getByRole('button', {name: 'Ruleta personalizada Crea y gira tu propia ruleta.', exact: true}).click();
  await page.getByRole('button', {name: 'Editar opciones', exact: true}).click();
  await page.getByRole('textbox', {name: 'Opciones, una por línea', exact: true}).fill('Pizza\nPollo\nEnsalada');
  await page.getByRole('button', {name: 'Agregar', exact: true}).click();
  check(await page.locator('#custom-option-list li').count() === 3, 'Bulk add failed');
  check(await page.locator('#option-label').inputValue() === '', 'Input was not cleared');
  await page.locator('#custom-option-list [data-option-action="remove"]').first().click();
  await page.locator('#confirm-action').click();
  await page.getByRole('button', {name: 'Deshacer', exact: true}).click();
  check(await page.locator('#custom-option-list li').count() === 3, 'Undo failed');
  await page.getByRole('button', {name: 'Cerrar editor de opciones', exact: true}).click();
  await page.getByRole('button', {name: 'JUGAR', exact: true}).click();
  check(await page.locator('#play-button').isDisabled(), 'Play not locked');
  check(await page.locator('#mode-selector').isDisabled(), 'Mode not locked');
  check(await page.locator('#edit-options-button').isDisabled(), 'Editor not locked');
  await page.locator('.result-card').filter({hasNotText: 'Sorteando'}).waitFor();
  await page.waitForFunction(() => !document.querySelector('#play-button').disabled);
  check(['Pizza', 'Pollo', 'Ensalada'].includes(await page.locator('.result-card').textContent()), 'Unexpected result');
  await page.screenshot({path: 'output/playwright/custom-mobile.png'});
  await page.setViewportSize({width: 844, height: 390});
  check(await page.locator('#play-button').isVisible(), 'CTA missing in landscape');
  check(await page.locator('#play-button').evaluate(el => el.getBoundingClientRect().bottom <= innerHeight), 'CTA clipped');
  await page.screenshot({path: 'output/playwright/custom-landscape.png'});
  await page.setViewportSize({width: 1280, height: 800});
  await page.screenshot({path: 'output/playwright/custom-desktop.png'});
  await page.locator('#mode-selector').click();
  await page.getByRole('button', {name: 'Número aleatorio Sortea un número dentro de un rango.', exact: true}).click();
  await page.getByRole('spinbutton', {name: 'Mínimo', exact: true}).fill('');
  await page.getByRole('button', {name: 'JUGAR', exact: true}).click();
  check((await page.locator('.error').textContent()).includes('Completa ambos'), 'Empty range accepted');
  await page.getByRole('spinbutton', {name: 'Mínimo', exact: true}).fill('0');
  await page.emulateMedia({reducedMotion: 'reduce'});
  await page.getByRole('button', {name: 'JUGAR', exact: true}).click();
  await page.waitForFunction(() => !document.querySelector('#play-button').disabled);
  check(/^\d+$/.test(await page.locator('.result-card').textContent()), 'Number play failed');
  await page.locator('#mode-selector').click();
  await page.getByRole('button', {name: 'Ruleta personalizada Crea y gira tu propia ruleta.', exact: true}).click();
  check(await page.locator('.wheel-legend li').count() === 3, 'Custom options lost');
  await page.reload();
  await page.locator('#mode-selector').click();
  await page.getByRole('button', {name: 'Ruleta personalizada Crea y gira tu propia ruleta.', exact: true}).click();
  check(await page.locator('.wheel-legend li').count() === 3, 'Persistence failed');
  const isolated = await page.context().newPage();
  await isolated.addInitScript(() => Object.defineProperty(window, 'localStorage', {get() {throw new Error('Storage blocked');}}));
  await isolated.goto('http://127.0.0.1:8088/web/');
  check(await isolated.getByRole('button', {name: 'JUGAR', exact: true}).isEnabled(), 'Blocked storage prevented startup');
  await isolated.close();
  return 'PASS: bulk add, undo, spin locks, result, layouts, range validation, reduced motion, persistence, blocked storage';
}
